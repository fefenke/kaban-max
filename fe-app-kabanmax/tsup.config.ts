import { defineConfig } from 'tsup';
import fs from 'fs';
import path from 'path';

export default defineConfig({
  entry: ['src/main.ts'],
  format: ['esm'],
  outDir: '../luci-app-kabanmax/htdocs/luci-static/resources/view/kabanmax',
  outExtension: () => ({ js: '.js' }),
  dts: false,
  clean: false,
  sourcemap: false,
  banner: {
    js: `// This file is autogenerated, please don't change manually \n"use strict";`,
  },
  esbuildOptions(options) {
    options.legalComments = 'none';
    options.minifyWhitespace = true;
    options.minifySyntax = true;
    // LuCI's export adapter keeps public names and its API readable.
    options.minifyIdentifiers = false;
  },
  onSuccess: () => {
    const outDir =
      '../luci-app-kabanmax/htdocs/luci-static/resources/view/kabanmax';
    const file = path.join(outDir, 'main.js');
    let code = fs.readFileSync(file, 'utf8');
    // LuCI discovers dependencies from complete directive lines.
    code = code.replace(/(?:"require [^"\r\n]+";)+/, (directives) =>
      directives.replaceAll(';', ';\n'),
    );

    code = code.replace(/export\s*{([\s\S]*?)}/, (match, group) => {
      return `return baseclass.extend({${group}})`;
    });

    fs.writeFileSync(file, code, 'utf8');
    console.log(`✅ Patched LuCI build: ${file}`);
  },
});
